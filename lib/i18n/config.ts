export function translate(
  locale: Locale,
  key: string,
  values?: TranslationValues,
) {
  let template = locale === "zh-CN" ? (zhCN[key] ?? key) : key;

  if (locale === "zh-CN" && template === key) {
    const dynamicPatterns: Array<[RegExp, (...parts: string[]) => string]> = [
      [/^Retrying safely \(attempt (\d+) of (\d+)\)\.\.\.$/, (_all, attempt, max) => `正在安全重试（第 ${attempt}/${max} 次）……`],
      [/^Attempt (\d+) did not finish\. Retrying once without using another quota\.\.\.$/, (_all, attempt) => `第 ${attempt} 次尝试未完成，正在进行一次不额外消耗额度的重试……`],
      [/^Because you saved questions about (.+)$/, (_all, tag) => `因为你收藏过与 ${tag} 相关的问题`],
      [/^Because you upvoted questions about (.+)$/, (_all, tag) => `因为你赞过与 ${tag} 相关的问题`],
      [/^Because you answered questions about (.+)$/, (_all, tag) => `因为你回答过与 ${tag} 相关的问题`],
      [/^Because you posted questions about (.+)$/, (_all, tag) => `因为你发布过与 ${tag} 相关的问题`],
      [/^Based on your recent activity in (.+)$/, (_all, tag) => `根据你最近在 ${tag} 相关内容中的活动推荐`],
    ];

    for (const [pattern, render] of dynamicPatterns) {
      const match = key.match(pattern);
      if (match) {
        template = render(...match);
        break;
      }
    }
  }

  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name])
      : match,
  );
}

export type Translator = (
  key: string,
  values?: TranslationValues,
) => string;
